import numpy as np
arr1=np.array([10,20,30])
arr2=np.array([1,2,3])
print("Array1: ",arr1)
print("Array2: ",arr2)
#Addition
print("\nAddition:")
print(arr1+arr2)
#Subtraction
print("\nSubtraction:")
print(arr1 - arr2)
#Multiplication
print("\nMultiplication:")
print(arr1 * arr2)
#Division
print("\nDivision:")
print(arr1 / arr2)

#Scalar Operations:
print("\nAdd 5:")
print(arr1 + 5)

print("\nMultiply by 2:")
print(arr1 * 2)

print("\nDivide by 10:")
print(arr1 / 10)